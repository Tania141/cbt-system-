const _kesZn = v => String(v ?? '').toLowerCase().replace(/[^0-9a-zа-я]+/g, '');

// Резюмето на записките → какво се предлага за всяко поле.
function _kesPredlozheni(r) {
    const out = {};
    for (const s of r.shapka || []) {
        if (!s.klyuch) continue;
        out[s.klyuch] = { stoynost: s.stoynost, edinno: s.edinno, varianti: s.varianti || [], iztochnik: null };
    }
    for (const v of r.priznaci || []) {
        const t = (v.tvardenia || [])[0] || {};
        out[v.priznak] = {
            stoynost: v.stoynost, edinno: v.edinno,
            varianti: (v.tvardenia || []).map(x => ({ stoynost: x.stoynost, chasti: [x.chast] })),
            iztochnik: { chast: t.chast || '', stranica: t.stranica, citat: t.citat || '' },
        };
    }
    // Възложителите от челния лист стават „собственик на земята“.
    const sobstv = (r.sobstvenici_ot_zapiski || []).filter(Boolean);
    if (sobstv.length) out.sobstvenik = { stoynost: sobstv.join(' · '), edinno: true, varianti: [],
        iztochnik: { chast: 'челен лист на проекта', citat: '' } };
    return out;
}

// Слива предложеното със склада, без да трие свереното.
function _kesSleej(p, predl) {
    const f = (p.fakti = p.fakti || {});
    let novi = 0;
    for (const [k, pr] of Object.entries(predl)) {
        if (!_KES_IME[k]) continue;
        const star = f[k];
        if (!pr.edinno) {                       // частите не се връзват
            // Ако операторът ВЕЧЕ е решил кой вариант е верен, решението му
            // остава — иначе всяко пререждане на екрана го изтриваше и полето
            // пак ставаше спорно. (02.10.2026, намерено от оператора)
            if (star && (star.sastoyanie === 'potvardeno' || star.sastoyanie === 'popraveno')) {
                f[k] = { ...star, varianti: pr.varianti };
                continue;
            }
            f[k] = { ...(star || {}), sastoyanie: 'sporno', stoynost: '', prochetena: '',
                     varianti: pr.varianti, iztochnik: pr.iztochnik };
            continue;
        }
        const svereno = star && (star.sastoyanie === 'potvardeno' || star.sastoyanie === 'popraveno');
        if (svereno && _kesZn(star.prochetena) === _kesZn(pr.stoynost)) {
            f[k] = { ...star, iztochnik: pr.iztochnik, varianti: null };   // същото е — не го пипаме
            continue;
        }
        if (svereno) {                          // ново четене дава друго → пак за потвърждение
            f[k] = { sastoyanie: 'predlozheno', stoynost: pr.stoynost, prochetena: pr.stoynost,
                     predishna: star.stoynost, iztochnik: pr.iztochnik, varianti: null };
            novi++;
            continue;
        }
        if (!star || _kesZn(star.prochetena) !== _kesZn(pr.stoynost)) novi++;
        f[k] = { sastoyanie: 'predlozheno', stoynost: pr.stoynost, prochetena: pr.stoynost,
                 iztochnik: pr.iztochnik, varianti: null };
    }
    return novi;
}

