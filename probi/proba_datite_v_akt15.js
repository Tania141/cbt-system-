// ДАТИТЕ В АКТ 15 — търсят се навсякъде, където са знайни.
//
// Операторът, 29.10.2026: „когато генерирам 15 с питон, там не се записва
// датата пр. 2, а има поле и има дата в системата“.
//
// Беше вярно: Протокол 2 и обр. 3 се вземаха САМО от ръчно попълненото поле
// „Дати на съставените документи“. Не го ли напълниш, в акта излиза [___] —
// макар датата да стои в сверения документ, който го доказва.
//
// Границата, която пробата пази: ръчното бие всичко (то е на оператора), а
// щом него го няма — датата идва от СВЕРЕНИЯ документ. И „2а“ не минава за „2“.
const { kod, grab } = require('./kod');
const s = kod();

const F = new Function(
    [grab(s, '_a15Vpisan'), grab(s, '_a15NomerData'), grab(s, '_a15DataNaDokument')].join('\n')
    + '\nconst P2 = ' + /протокол\s*(обр\.?|образец)?\s*№?\s*2(?![\dа-я])|откриване на строителна площадка/i.source.length
    + ';\nreturn {_a15Vpisan,_a15NomerData,_a15DataNaDokument};')();

// Изразите се вадят от самия код — ако някой ги смени, пробата ги следва.
const izraz = ime => {
    const m = new RegExp('const ' + ime + ' = (/.+/i);').exec(s);
    if (!m) throw new Error('няма израз ' + ime);
    return eval(m[1]);                                  // eslint-disable-line no-eval
};
const P2 = izraz('_A15_PROTOKOL_2');
const P2A = izraz('_A15_PROTOKOL_2A');
const O3 = izraz('_A15_OBRAZEC_3');

const dobri = [], loshi = [];
const t = (ime, verno, kak) => (verno ? dobri : loshi).push(ime + (verno ? '' : '  → ' + JSON.stringify(kak)));

const dok = (ime, nomer, red) => ({ ime, nomer, red: red || '' });

// ── ръчното бие всичко ──────────────────────────────────────────────────────
const p1 = { dokumenti: [dok('Протокол за откриване на строителна площадка', '№ 1 от 15.03.2022')] };
t('ръчно попълнената дата бие прочетената',
  F._a15DataNaDokument(p1, { protokol2: '20.01.2022' }, 'protokol2', P2) === '20.01.2022');

// ── без ръчно — идва от сверения документ ───────────────────────────────────
t('без ръчно идва от сверения документ',
  F._a15DataNaDokument(p1, {}, 'protokol2', P2) === '15.03.2022',
  F._a15DataNaDokument(p1, {}, 'protokol2', P2));
t('празни дати не гърмят',
  F._a15DataNaDokument({ dokumenti: [] }, {}, 'protokol2', P2) === '');
t('обект без документи не гърми',
  F._a15DataNaDokument({}, {}, 'protokol2', P2) === '');

// ── намира се и по РЕДА от чеклиста, не само по името ───────────────────────
const p2 = { dokumenti: [dok('Приложение № 2 към чл. 7, ал. 3, т. 2', '№ 7 от 12.12.2025',
                             'Протокол обр. 2')] };
t('намира се и по реда, който документът доказва',
  F._a15DataNaDokument(p2, {}, 'protokol2', P2) === '12.12.2025',
  F._a15DataNaDokument(p2, {}, 'protokol2', P2));

// ── „2а“ НЕ минава за „2“ — това е същината ─────────────────────────────────
const p2a = { dokumenti: [dok('Протокол обр. 2а за откриване', '№ 3 от 04.07.2025')] };
t('протокол 2а не се взема за протокол 2',
  !P2.test('Протокол обр. 2а за откриване'), 'P2 хваща 2а');
t('а 2а се намира със своя израз',
  F._a15DataNaDokument(p2a, {}, 'protokol2', P2A) === '04.07.2025',
  F._a15DataNaDokument(p2a, {}, 'protokol2', P2A));
t('и протокол 2 не минава за 2а',
  !P2A.test('Протокол обр. 2 за откриване'));

// ── констативен акт обр. 3 ──────────────────────────────────────────────────
const p3 = { dokumenti: [dok('Констативен акт обр. 3', '№ 1 от 07.10.2022')] };
t('обр. 3 се намира', F._a15DataNaDokument(p3, {}, 'obrazec3', O3) === '07.10.2022',
  F._a15DataNaDokument(p3, {}, 'obrazec3', O3));
t('акт обр. 14 НЕ минава за обр. 3',
  !O3.test('Акт обр. 14 за приемане на конструкцията'));
t('акт обр. 15 НЕ минава за обр. 3',
  !O3.test('Акт обр. 15'));
t('обр. 3 не хваща обр. 7',
  !O3.test('Акт обр. 7'));

// ── и старият път си работи ─────────────────────────────────────────────────
const p4 = { dokumenti: [dok('Договор за СМР', '№ 12 от 01.03.2026')] };
t('_a15Vpisan още намира по име',
  F._a15Vpisan(p4, /договор.*смр/i) === '№ 12 от 01.03.2026');
t('_a15Vpisan вече намира и по ред',
  F._a15Vpisan({ dokumenti: [dok('Писмо на „Софийска вода“', '№ 5 от 01.01.2026',
                                 'Становище за СВО')] }, /становище за сво/i)
  === '№ 5 от 01.01.2026');

dobri.forEach(x => console.log('  ok  ' + x));
loshi.forEach(x => console.log('  ЛО  ' + x));
console.log(loshi.length ? `\n${loshi.length} проблема` : `\n${dobri.length} проверки — датите се намират`);
process.exit(loshi.length ? 1 : 0);
