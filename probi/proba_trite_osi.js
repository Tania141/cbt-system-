// ТРИТЕ ОСИ НА ЕКРАНА.
//
// АТ, 30.10.2026: приложимост, наличие и приемане са три различни въпроса и не
// се смесват. Дотук екранът показваше ЕДИН списък — „Не е намерено сред
// прочетените“ — и в него влизаше само „не е доказано“. Редовете „не се
// отнася“ бяха невидими.
//
// Цената се видя на истински линеен обект: липсващ акт обр. 7 за фундамента на
// БКТП изглеждаше точно като липсващ акт обр. 14, който наистина не се отнася.
// Едното е пропуск, другото е вярно — и двете изглеждаха еднакво.
const { kod, grab } = require('./kod');
const s = kod();

const F = new Function(
    "const _s2esc = x => String(x ?? '');\n"
    + (new RegExp('^const _CHEKLIST_GRUPI = [\\s\\S]*?\\n\\];$', 'm').exec(s) || [''])[0] + '\n'
    + (new RegExp('^const _CHEKLIST_ZASHTO = \\{[\\s\\S]*?\\n\\};$', 'm').exec(s) || [''])[0] + '\n'
    + [grab(s, '_cheklistOs'), grab(s, '_cheklistPoOsiHtml')].join('\n')
    + '\nreturn {_cheklistOs, _cheklistPoOsiHtml};')();

const dobri = [], loshi = [];
const t = (ime, verno, kak) => (verno ? dobri : loshi).push(ime + (verno ? '' : '  → ' + JSON.stringify(kak)));

const os = (prilozhimost, nalichie, zashto) => ({ prilozhimost, nalichie, zashto: zashto || '' });

// ── точно случаят от линейния обект ─────────────────────────────────────────
const C = {
    iziskvani: 4,
    redove: [
        { dokument: 'Акт обр. 7', osi: os('изисква се', 'липсва') },
        { dokument: 'Акт обр. 14', osi: os('не е приложимо', 'не е проверено', 'оператор') },
        { dokument: 'Протокол обр. 17', osi: os('условно приложимо', 'не е проверено') },
        { dokument: 'Заповедна книга', osi: os('изисква се', 'частично намерено') },
        { dokument: 'Протокол обр. 2', osi: os('изисква се', 'намерено') },
    ],
};
const h = F._cheklistPoOsiHtml(C);

t('липсващото и неприложимото вече НЕ изглеждат еднакво',
  h.indexOf('Акт обр. 7') < h.indexOf('Акт обр. 14'), '');
// Всеки ред стои под СВОЕТО заглавие, не под общото „не е намерено“.
const gol = h.replace(/<[^>]+>/g, ' ');
const sled = (zagl, red) => {
    const i = gol.indexOf(zagl), j = gol.indexOf(red);
    return i >= 0 && j > i && !/Липсва|Частично|Условно|Не е приложимо/
        .test(gol.slice(i + zagl.length, j));
};
t('акт обр. 7 е под „Липсва“', sled('Липсва', 'Акт обр. 7'), '');
t('акт обр. 14 е под „Не е приложимо“', sled('Не е приложимо', 'Акт обр. 14'), '');
t('протокол обр. 17 е под „Условно приложимо“',
  sled('Условно приложимо', 'Протокол обр. 17'), '');
for (const ime of ['Липсва', 'Частично намерено', 'Условно приложимо', 'Не е приложимо'])
    t(`групата „${ime}“ е на екрана`, h.includes(ime));

t('неприложимото казва ЗАЩО е такова', h.includes('ти си го отбелязала'), '');
t('намереното не се показва като проблем', !h.includes('Протокол обр. 2'), '');
t('броят на липсващото е от изискваните', h.includes('Липсва — 1 от 4'), '');

// ── празните групи не се рисуват ────────────────────────────────────────────
const samoNalichni = F._cheklistPoOsiHtml({
    iziskvani: 1, redove: [{ dokument: 'РС', osi: os('изисква се', 'намерено') }] });
t('без проблеми екранът мълчи', samoNalichni === '', samoNalichni);

// ── стар отговор от сървъра още се чете ─────────────────────────────────────
// Сървърът може да е по-стар от ПВА-то — тогава реда носи само състоянието.
t('„не се отнася“ без оси става неприложимо от оператора',
  F._cheklistOs({ sastoyanie: 'не се отнася' }).prilozhimost === 'не е приложимо'
  && F._cheklistOs({ sastoyanie: 'не се отнася' }).zashto === 'оператор');
t('„не се изисква“ без оси става неприложимо по условие',
  F._cheklistOs({ sastoyanie: 'не се изисква' }).zashto === 'условие');
t('„за преценка“ без оси става условно приложимо',
  F._cheklistOs({ sastoyanie: 'за преценка' }).prilozhimost === 'условно приложимо');
t('„налице“ без оси става намерено',
  F._cheklistOs({ sastoyanie: 'налице' }).nalichie === 'намерено');
t('„не е доказано“ без номер става частично намерено',
  F._cheklistOs({ sastoyanie: 'не е доказано', lipsva_nomer: true }).nalichie === 'частично намерено');
t('„не е доказано“ без вписан става липсва',
  F._cheklistOs({ sastoyanie: 'не е доказано' }).nalichie === 'липсва');
t('а щом сървърът праща оси, те бият състоянието',
  F._cheklistOs({ sastoyanie: 'не е доказано', osi: os('не е приложимо', 'не е проверено', 'условие') })
      .prilozhimost === 'не е приложимо');

dobri.forEach(x => console.log('  ok  ' + x));
loshi.forEach(x => console.log('  ЛО  ' + x));
console.log(loshi.length ? `\n${loshi.length} проблема` : `\n${dobri.length} проверки — трите оси се виждат поотделно`);
process.exit(loshi.length ? 1 : 0);
