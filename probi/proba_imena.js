// Имената от официалните регистри.
//
// КИИП и регистърът на техническия контрол са публикувани с ГЛАВНИ букви.
// Досега избраното име влизаше в акта като „Абдулла мохамед ждид“ — главна
// само първата буква на реда. (Операторът, 19.10.2026.)
const { kod, grab, parche } = require('./kod');
const s = kod();
const F = new Function(parche(s, 'const _MALKI_DUMI', 'async function registar')
    + '\nreturn { imeSGlavni };')();

const dobri = [], loshi = [];
const t = (ime, verno, kak) => (verno ? dobri : loshi).push(ime + (verno ? '' : '  → ' + JSON.stringify(kak)));
const g = F.imeSGlavni;

t('всяка дума със своя главна буква',
  g('АБДУЛЛА МОХАМЕД ЖДИД') === 'Абдулла Мохамед Ждид', g('АБДУЛЛА МОХАМЕД ЖДИД'));
t('двойната фамилия също',
  g('АВГУСТИНА СТЕФАНОВА ХРИСТОВА-ДИМОВА') === 'Августина Стефанова Христова-Димова',
  g('АВГУСТИНА СТЕФАНОВА ХРИСТОВА-ДИМОВА'));
t('излишните интервали падат', g('ИВАН   ПЕТРОВ ') === 'Иван Петров', g('ИВАН   ПЕТРОВ '));
t('вече написано правилно не се чупи',
  g('Надя Йорданова Спасова') === 'Надя Йорданова Спасова', g('Надя Йорданова Спасова'));
t('апострофът е като тирето', g("Д'АРТАНЯН ПЕТРОВ") === "Д'Артанян Петров", g("Д'АРТАНЯН ПЕТРОВ"));
t('празното си остава празно', g('') === '' && g(null) === '');
t('фирма с „и“ не получава главна в средата и формата остава',
  g('ПЕТРОВ И СИН ООД') === 'Петров и Син ООД', g('ПЕТРОВ И СИН ООД'));

dobri.forEach(x => console.log('  ok  ' + x));
loshi.forEach(x => console.log('  ЛО  ' + x));
console.log(loshi.length ? `\n${loshi.length} проблема` : `\n${dobri.length} проверки — имената са с главни букви по дума`);
process.exit(loshi.length ? 1 : 0);
